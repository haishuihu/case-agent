"""追加生成 Prompt 模板 - Sprint 4"""

SYSTEM_PROMPT_APPEND = """你是一个资深测试工程师，需要根据已有的测试用例和需求描述，分析遗漏的场景并补充用例。

## 你的任务
1. 仔细阅读已有用例，找出其覆盖范围
2. 分析需求描述中是否有已有用例未覆盖的场景
3. 补充遗漏的用例，确保覆盖完整

## 分析维度
1. **覆盖完整性**: 正常流程、异常流程、边界条件是否都有覆盖
2. **场景完整性**: 功能路径、数据处理、接口兼容、并发、安全等维度
3. **遗漏分析**: 明确说明为什么某个场景被遗漏了

## 输出规范
- 只输出 JSON，不要附加任何解释文字
- 优先补充高风险、高频使用的遗漏场景
- 每个补充用例说明遗漏原因
"""

SYSTEM_PROMPT_APPEND_DIMENSIONS = """## 补充场景维度（请逐一检查）
- 正常流程：核心功能路径是否完整
- 异常场景：网络异常、超时、服务不可用、数据异常
- 边界条件：空值、边界值、超长输入、特殊字符
- 并发场景：多用户同时操作、并发修改
- 安全场景：权限校验、SQL注入、XSS、越权访问
- 性能场景：大数据量、响应时间、并发压力
- 数据一致性：缓存与数据库一致性、多端数据同步
"""


def build_append_prompt(existing_cases: str, requirement_text: str) -> str:
    """构建追加生成的 prompt"""
    return f"""## 已有测试用例

```markdown
{existing_cases[:8000]}
```

---

## 需求描述

{requirement_text}

---

## 任务

请分析已有用例的覆盖情况，补充遗漏的场景。

{SYSTEM_PROMPT_APPEND_DIMENSIONS}

## 输出要求

请只输出JSON格式：
{{
  "summary": "补充说明：本轮共补充了X个遗漏场景，主要包括...",
  "appended_cases": [
    {{
      "title": "用例标题（中文）",
      "category": "分类（正常流程/异常场景/边界条件/并发测试/安全测试/性能测试）",
      "priority": "优先级（P0/P1/P2）",
      "module": "所属模块",
      "preconditions": ["前置条件1", "前置条件2"],
      "steps": ["步骤1", "步骤2", "步骤3"],
      "expected_result": "预期结果",
      "missing_reason": "为什么这个用例被遗漏了"
    }}
  ]
}}
"""
