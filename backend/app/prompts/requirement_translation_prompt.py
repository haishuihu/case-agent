# ---------------------------------------------------------------------------
# Prompt builder
# ---------------------------------------------------------------------------


def build_requirement_translation_prompt(
    requirement_text: str,
    document_contexts: list[DocumentContext] | None = None,
) -> str:
    """Build the full prompt for translating raw requirements into structured format."""
    document_contexts = document_contexts or []

    # Build requirement context
    requirement_block = (
        requirement_text.strip()
        or "未提供单独的文字需求描述，请以参考文档中的功能说明、业务规则与约束为准。"
    )

    document_sections: list[str] = []
    for idx, doc in enumerate(document_contexts, start=1):
        document_sections.append(
            "\n".join(
                [
                    f"### 参考文档 {idx}",
                    f"- 文件名：{doc.filename}",
                    f"- 类型：{doc.content_type}",
                    "- 内容摘录：",
                    doc.extracted_text or "(无可提取文本)",
                ]
            )
        )
    documents_block = (
        "\n\n".join(document_sections) if document_sections else "无额外参考文档。"
    )

    return "\n\n".join(
        [
            "## 原始需求",
            requirement_block,
            "## 参考文档",
            documents_block,
            "---",
            "## 任务：将原始需求翻译为结构化需求规格说明",
            "",
            "请严格按照以下规范执行：",
            "",
            "### 第一步：通读理解",
            "通读原始需求全文，理解业务目标和核心功能。",
            "",
            "### 第二步：模块识别",
            "将需求拆分为独立的功能模块（M01, M02...）。",
            "模块划分原则：可独立测试、边界清晰、领域内聚。",
            "",
            "### 第三步：逐模块分析",
            "对每个模块，从原文中提取：需求点、交互流程、数据字段、业务规则。",
            "**关键规则：**",
            "- 只提取原文中明确描述的内容，绝不凭空编造。",
            "- 原文中不完整、模糊、矛盾的内容，标注 ⚠️ 并以疑问句写入「待确认问题」。",
            "- 原文中完全未涉及的维度（如交互流程、数据约束），标注「原需求未涉及」并以疑问句写入「待确认问题」。",
            "- 如果原文只有零散的描述，不要试图补全成一个完整的「故事」，忠实还原原文的完整度即可。",
            "",
            "### 第四步：全局约束提取",
            "从原文中提取跨模块的全局性约束（权限、性能、兼容性、安全）。",
            "原文未涉及的维度，统一以疑问句提出。",
            "",
            "### 第五步：生成汇总",
            "汇总所有待确认问题到第 6 节，生成审查清单。",
            "",
            "### 输出格式",
            "严格按照以下 Markdown 模板输出，不要添加额外的解释文字：",
            "",
            OUTPUT_TEMPLATE.format(
                requirement_source="[原始需求文件名或链接]",
                translation_date="YYYY-MM-DD",
            ),
        ]
    )


def build_requirement_context_for_translation(
    requirement_text: str, document_contexts: list[DocumentContext]
) -> str:
    """Build just the requirement + document context block (reusable)."""
    requirement_block = (
        requirement_text.strip()
        or "未提供单独的文字需求描述，请以参考文档中的功能说明、业务规则与约束为准。"
    )

    document_sections: list[str] = []
    for idx, doc in enumerate(document_contexts, start=1):
        document_sections.append(
            "\n".join(
                [
                    f"### 参考文档 {idx}",
                    f"- 文件名：{doc.filename}",
                    f"- 类型：{doc.content_type}",
                    "- 内容摘录：",
                    doc.extracted_text or "(无可提取文本)",
                ]
            )
        )
    documents_block = (
        "\n\n".join(document_sections) if document_sections else "无额外参考文档。"
    )

    return "\n\n".join(
        ["## 功能需求", requirement_block, "## 参考文档", documents_block]
    )
